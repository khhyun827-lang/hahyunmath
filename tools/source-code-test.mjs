// 모의고사 기출 + 변형 교재(주기나 꼴)의 코드 만들기 검사 (2026-09-05)
//
//   node tools/source-code-test.mjs
//
// 사용자 요청 — 「2017년 09월 21번 라고하는 출처가 있어 이를통해서 1(학년)17(년)09(월)21(번)OR
// 이런식으로 코드를 붙이고싶어. 교재의 문항별 우측상단에 OR DW NC UP 라고 하는 그림이 있어.」
//
// 🔴 **딱지는 «글»이 아니라 «그림»이다.** 글자로는 못 읽는다 — 그림의 해시로 알아본다.
//    참조 이름(image8)에 기대면 안 된다(파일마다 다르다). shapeComment 도 못 쓴다(넷 다 「번호.png」).
// 🔵 **스스로 검사할 길이 있다** — 원본(OR)은 출처 묶음마다 정확히 하나여야 한다.
//    실측한 파일: 서로 다른 출처 24개 · OR 24개 · 모든 묶음에 하나씩. 그 셈으로 딱지를 검산한다.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { loadHwpxRules } from './hwpx-node.mjs';

const R = loadHwpxRules();
let pass = 0, fail = 0;
const 봄 = (무엇, 나온것, 나와야할것) => {
  const ok = JSON.stringify(나온것) === JSON.stringify(나와야할것);
  if (ok) { pass++; console.log('  ✓ ' + 무엇); }
  else { fail++; console.log(`  ✗ ${무엇}\n      나온 것: ${JSON.stringify(나온것)}\n      나와야:  ${JSON.stringify(나와야할것)}`); }
};

console.log('\n출처와 딱지로 코드 만들기\n');

// ── 출처 읽기 ────────────────────────────────────────────────────────
봄('「2023년 09월 28번」을 읽는다', R.hwpxParseSourceTag('2023년 09월 28번'), { 년:'23', 월:'09', 번:'28' });
봄('번호가 한 자리면 두 자리로 맞춘다', R.hwpxParseSourceTag('2017년 09월 8번').번, '08');
봄('월이 한 자리여도 맞춘다', R.hwpxParseSourceTag('2017년 3월 21번').월, '03');
봄('출처가 아니면 null', R.hwpxParseSourceTag('고쟁이'), null);

// 🔵 학년은 «몇 월 시행이냐»가 정한다 (사용자가 정했다)
봄('3월 출처는 2학년', R.hwpxGradeOfMonth('03'), '2');
봄('9월 출처는 1학년', R.hwpxGradeOfMonth('09'), '1');
봄('11월 출처도 1학년', R.hwpxGradeOfMonth('11'), '1');

// ── 코드 만들기 ──────────────────────────────────────────────────────
const 것 = (년, 월, 번, 딱지) => ({ 출처:{ 년, 월, 번 }, 딱지들:[딱지] });
{
  const r = R.hwpxMakeSourceCodes([것('23','09','28','OR'), 것('23','09','28','NC'),
                                   것('23','09','28','UP'), 것('23','09','28','UP')]);
  봄('원본은 번호를 안 붙인다', r.codes[0], '1230928OR');
  // 🔵 사용자가 (가)를 골랐다 — 변형은 «언제나» 두 자리. 규칙이 하나여야 한다
  봄('변형은 언제나 두 자리', r.codes[1], '1230928NC01');
  봄('같은 딱지가 둘이면 01·02', [r.codes[2], r.codes[3]], ['1230928UP01', '1230928UP02']);
}
{
  const r = R.hwpxMakeSourceCodes([것('05','03','10','OR'), 것('05','03','10','NC')]);
  봄('3월 출처는 2로 시작한다', r.codes, ['2050310OR', '2050310NC01']);
}
// ── 🔴 스스로 멈추는 자리 ────────────────────────────────────────────
{
  const r = R.hwpxMakeSourceCodes([것('23','09','28','NC'), 것('23','09','28','UP')]);
  봄('🔴 원본이 없으면 멈춘다', r.ok, false);
  봄('까닭을 말한다', /원본\(OR\)이 하나가 아닙니다/.test(r.흠[0]), true);
}
{
  const r = R.hwpxMakeSourceCodes([것('23','09','28','OR'), 것('23','09','28','OR')]);
  봄('🔴 원본이 둘이어도 멈춘다 (딱지를 잘못 읽었다는 뜻)', r.ok, false);
}
{
  const r = R.hwpxMakeSourceCodes([{ 출처:{년:'23',월:'09',번:'28'}, 딱지들:[] }]);
  봄('🔴 딱지가 없으면 멈춘다', r.ok, false);
  봄('몇 번째인지 말한다', /1번째/.test(r.흠[0]), true);
}
{
  const r = R.hwpxMakeSourceCodes([{ 출처:{년:'23',월:'09',번:'28'}, 딱지들:['OR','NC'] }]);
  봄('🔴 딱지가 둘이면 멈춘다 — 조용히 하나를 고르지 않는다', r.ok, false);
  봄('둘이라고 말한다', /딱지가 2개/.test(r.흠[0]), true);
}
{
  // 🔵 목차·표지에도 미주가 붙는다 — 출처도 딱지도 없으면 «문항이 아니다»
  const r = R.hwpxMakeSourceCodes([{ 출처:null, 딱지들:[] }, 것('23','09','28','OR')]);
  봄('🔵 문항이 아닌 덩이는 조용히 지나간다', r.codes, ['1230928OR']);
}

// ── 🔴 지퍼 맞추기 (한 칸 밀림) ──────────────────────────────────────
// 사용자가 「미주가 71개인데 70개로 인식된거야?」라고 물어서 찾은 흠이다.
// 파일 안 차례는 [미주][딱지][출처] [미주][딱지][출처] … — 머리말이 그 문항 «뒤»에 적힌다
// (화면에서는 우측 상단이지만, 떠 있는 개체라 글보다 뒤에 적힌다).
// 「앞에서 마지막으로 본 출처」를 쓰면 **첫 문항이 통째로 빠지고 마지막 딱지가 주인 없이 남는다.**
{
  const 셈붙임 = (a, 셈) => { a.셈 = 셈; return a; };
  const r = R.hwpxMakeSourceCodes(셈붙임([것('23','09','28','OR'), 것('23','09','28','NC')],
                                        { 미주:2, 출처:2, 딱지:2 }));
  봄('🔵 미주·출처·딱지 수가 같으면 차례대로 짝짓는다', r.codes, ['1230928OR', '1230928NC01']);
}
{
  const a = [것('23','09','28','OR')]; a.셈 = { 미주:71, 출처:70, 딱지:71 };
  const r = R.hwpxMakeSourceCodes(a);
  봄('🔴 셋의 수가 다르면 멈춘다 — 한 칸 밀린 채로 코드를 붙이지 않는다', r.ok, false);
  봄('세 수를 다 말한다', /미주 71 · 출처 70 · 딱지 71/.test(r.흠[0]), true);
}

console.log(`\n  ${fail ? '🔴' : '✅'} ${pass} 통과 · ${fail} 실패\n`);
process.exit(fail ? 1 : 0);
