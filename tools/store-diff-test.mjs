// 창고 대조 판정을 잰다 — 여덟 갈래가 제 갈래로 가나 (2026-09-09)
//
//   node tools/store-diff-test.mjs
//
// 🔴 **함수를 여기에 옮겨 적지 않는다.** 루트 `hwpx.js` 에서 그대로 떠 온다 —
//    베껴 적는 순간 «검사는 통과하는데 실물은 다른» 자리가 생긴다.
//
// 🔵 **재는 것은 «맞게 가르나»보다 «망가뜨리면 무나»다.** 판정이 조용히 통과시키는 것이
//    이 일에서 제일 비싼 사고다 — 창고에 중복이 들어가고, 그것은 되돌리기 어렵다.
//    그래서 갈래마다 «그렇게 되면 안 되는 짝»을 같이 넣어 둔다.
//
// 갈래와 까닭 → docs/코드-숨기기.md 0-B · 0-C

import { loadHwpxRules } from './hwpx-node.mjs';

const r = loadHwpxRules();
const 가른다 = r.hwpItemVerdicts;
const 막는다 = r.hwpVerdictBlockers;

let 통과 = 0, 실패 = 0;
function 잰다(이름, 참인가) {
  if (참인가) { 통과++; console.log('  ✓ ' + 이름); }
  else { 실패++; console.log('  ✗ ' + 이름); }
}
function 절(이름) { console.log('\n' + 이름); }

/* 창고 하나를 짓는다 — 코드 → 문서 */
function 창고(...쌍) {
  const o = {};
  for (const [code, content] of 쌍) o[code] = { code, content };
  return o;
}
const 문 = (code, content) => ({ code, content });

const A = '좌표평면 위의 두 점 A(1,2), B(4,6) 사이의 거리를 구하시오.';
const B = '직선 y=2x+1 에 평행하고 점 (0,3) 을 지나는 직선의 방정식은?';
const C = '집합 A={1,2,3} 의 부분집합의 개수는?';

// ── ② 그대로 ──────────────────────────────────────────────────────────
절('② 그대로 — 아무것도 안 한다');
{
  const v = 가른다([문('K2-01-E-0001', A)], 창고(['K2-01-E-0001', A]));
  잰다('본문이 같으면 «그대로»다', v.그대로.length === 1 && v.고쳤다.length === 0);
  잰다('그대로면 새 문항이 아니다', v.새문항.length === 0);

  const v2 = 가른다([문('K2-01-E-0001', '  ' + A.replace(' ', '\n  ') + ' \n')], 창고(['K2-01-E-0001', A]));
  잰다('🔵 줄바꿈·두 칸·앞뒤 공백에는 «고쳤다»가 안 뜬다', v2.그대로.length === 1);

  const v3 = 가른다([문('K2-01-E-0001', A.replace('1,2', '1,3'))], 창고(['K2-01-E-0001', A]));
  잰다('⚠ 숫자 하나가 바뀌면 «그대로»가 아니다(=검사가 문다)', v3.그대로.length === 0 && v3.고쳤다.length === 1);
}

// ── ③ 고쳤다 ──────────────────────────────────────────────────────────
절('③ 고쳤다 — 옛글과 새글을 둘 다 돌려준다');
{
  const 새글 = A.replace('구하시오.', '구하여라.');
  const v = 가른다([문('K2-01-E-0001', 새글)], 창고(['K2-01-E-0001', A]));
  잰다('«고쳤다» 한 건', v.고쳤다.length === 1);
  잰다('🔵 옛글을 들고 온다 — 이것이 있어야 나란히 보여 준다', v.고쳤다[0].옛글 === A);
  잰다('새글도 들고 온다', v.고쳤다[0].새글 === 새글);
  잰다('«고쳤다»는 막지 않는다 — 경보가 아니다', 막는다(v).length === 0);
}

// ── ① 복사됐다 ────────────────────────────────────────────────────────
절('① 복사됐다 — 한 코드가 두 문항을 가리킨다');
{
  const v = 가른다([문('K2-01-E-0001', A), 문('K2-01-E-0001', B)], 창고(['K2-01-E-0001', A]));
  잰다('«복사됨» 한 무리', v.복사됨.length === 1 && v.복사됨[0].무리.length === 2);
  잰다('🔴 복사본은 «그대로»로도 «고쳤다»로도 안 샌다', v.그대로.length === 0 && v.고쳤다.length === 0);
  잰다('🔴 복사가 있으면 아무것도 안 올린다', 막는다(v).some(x => x.갈래 === '복사됨'));
}

// ── ④ 모르는 코드 ─────────────────────────────────────────────────────
절('④ 모르는 코드 — 창고에 없다');
{
  const v = 가른다([문('K2-01-E-9999', A)], 창고(['K2-01-E-0001', B]));
  잰다('«모르는코드» 한 건', v.모르는코드.length === 1);
  잰다('🔴 새 문항으로 안 샌다 — 코드가 있으니 새것이 아니다', v.새문항.length === 0);
  잰다('🔴 모르는 코드가 있으면 아무것도 안 올린다', 막는다(v).some(x => x.갈래 === '모르는코드'));
}

// ── ⑤ 코드를 잃었다 ───────────────────────────────────────────────────
절('⑤ 코드를 잃었다 — 본문이 창고와 똑같다');
{
  const v = 가른다([문('', A)], 창고(['K2-01-E-0001', A], ['K2-01-E-0002', B]));
  잰다('«코드잃음» 한 건', v.코드잃음.length === 1);
  잰다('🔵 잃은 코드를 짚어 준다', v.코드잃음[0].후보[0] === 'K2-01-E-0001');
  잰다('갈리지 않는다', v.코드잃음[0].갈림 === false);
  잰다('🔴 새 문항으로 안 샌다 — 이것이 중복을 막는 자리다', v.새문항.length === 0);
  잰다('한 벌로 짚히면 막지 않는다', 막는다(v).length === 0);

  const v2 = 가른다([문('', A)], 창고(['K2-01-E-0001', A], ['K2-01-E-0002', A]));
  잰다('⚠ 본문이 같은 창고 문항이 둘이면 «갈림»이다 (0311=0314)', v2.코드잃음[0].갈림 === true);
  잰다('🔴 갈리면 아무것도 안 올린다 — 기계가 못 정한다', 막는다(v2).some(x => x.갈래 === '갈린 되찾기'));
}

// ── ⑤ 의 함정 — 코드를 «지운» 복사본 ──────────────────────────────────
절('⑤ 의 함정 — 코드를 지운 복사본에 그 코드를 도로 주면 안 된다');
{
  const v = 가른다([문('K2-01-E-0001', A), 문('', A)], 창고(['K2-01-E-0001', A]));
  잰다('🔴 되찾기가 스스로 복사를 만들지 않는다', v.코드잃음.length === 0);
  잰다('«복사됨»으로 떨어진다', v.복사됨.length === 1 && v.복사됨[0].코드지움 === true);
  잰다('🔴 그래서 아무것도 안 올린다', 막는다(v).some(x => x.갈래 === '복사됨'));
}

// ── ⑥ 새 문항 ─────────────────────────────────────────────────────────
절('⑥ 새 문항 — 창고 어디와도 다르다');
{
  const v = 가른다([문('', C)], 창고(['K2-01-E-0001', A], ['K2-01-E-0002', B]));
  잰다('«새문항» 한 건', v.새문항.length === 1);
  잰다('🔵 새 문항만으로는 안 막는다 — 이것이 「추가된 것만 받기」다', 막는다(v).length === 0);
  잰다('코드잃음으로 안 샌다', v.코드잃음.length === 0);
}

// ── ⑦ 겹친 문항 ───────────────────────────────────────────────────────
절('⑦ 코드는 다른데 본문이 같다');
{
  const v = 가른다([문('K2-03-E-0311', A), 문('K2-03-E-0314', A)],
                   창고(['K2-03-E-0311', A], ['K2-03-E-0314', A]));
  잰다('«겹침» 한 무리 · 코드 둘', v.겹침.length === 1 && v.겹침[0].length === 2);
  잰다('🔵 둘 다 «그대로»이기도 하다 — 겹침은 경보지 잠금이 아니다', v.그대로.length === 2);
  잰다('겹침만으로는 안 막는다', 막는다(v).length === 0);
}

// ── ⑧ 빠졌다 ──────────────────────────────────────────────────────────
절('⑧ 창고에 있는데 파일에 없다 — 절대 안 지운다, 세기만 한다');
{
  const v = 가른다([문('K2-01-E-0001', A)], 창고(['K2-01-E-0001', A], ['K2-01-E-0002', B]));
  잰다('«빠졌다» 한 건', v.빠졌다.length === 1 && v.빠졌다[0] === 'K2-01-E-0002');
  잰다('🔵 빠진 것으로는 안 막는다 — 지우는 일이 아니다', 막는다(v).length === 0);

  const v2 = 가른다([문('K2-01-E-0001', A)],
                    창고(['K2-01-E-0002', B], ['K2-05-E-0500', C], ['K2-02-E-0100', C]));
  잰다('🔴 테두리를 긋는다 — 딴 단원은 «빠졌다»가 아니다', v2.빠졌다.length === 1 && v2.빠졌다[0] === 'K2-01-E-0002');

  const v3 = 가른다([문('1230928OR', A)], 창고(['1230928OR', A], ['1230928NC01', B]));
  잰다('⚠ ②꼴 코드는 테두리를 못 그어 세지 않는다', v3.빠졌다.length === 0);
}

// ── 섞어서 — 한 파일에 여덟 갈래가 같이 온다 ──────────────────────────
절('섞어서 — 갈래가 서로 안 샌다');
{
  const v = 가른다([
    문('K2-01-E-0001', A),                    // ② 그대로
    문('K2-01-E-0002', B + ' 고침'),           // ③ 고쳤다
    문('K2-01-E-0003', C), 문('K2-01-E-0003', A + '!'),  // ① 복사
    문('K2-01-E-8888', '모르는 것'),           // ④
    문('', C + ' 딴것'),                       // ⑥ 새 문항
  ], 창고(['K2-01-E-0001', A], ['K2-01-E-0002', B], ['K2-01-E-0003', C], ['K2-01-E-0004', '빠질 것']));
  잰다('그대로 1', v.그대로.length === 1);
  잰다('고쳤다 1', v.고쳤다.length === 1);
  잰다('복사됨 1무리', v.복사됨.length === 1);
  잰다('모르는코드 1', v.모르는코드.length === 1);
  잰다('새문항 1', v.새문항.length === 1);
  잰다('빠졌다 1', v.빠졌다.length === 1 && v.빠졌다[0] === 'K2-01-E-0004');
  잰다('🔴 막을 것이 둘 — 복사와 모르는 코드', 막는다(v).length === 2);
  const 센것 = v.그대로.length + v.고쳤다.length + v.모르는코드.length
             + v.코드잃음.length + v.새문항.length + v.복사됨.reduce((a, x) => a + x.무리.length, 0);
  잰다('🔴 문항 여섯이 한 갈래씩 «빠짐없이» 들어갔다', 센것 === 6);
}

// ── 빈 것·이상한 것 ───────────────────────────────────────────────────
절('빈 것과 이상한 것에 안 넘어진다');
{
  잰다('빈 목록', 가른다([], {}).새문항.length === 0);
  잰다('창고가 없어도 선다', 가른다([문('K2-01-E-0001', A)], null).모르는코드.length === 1);
  잰다('본문이 빈 문항은 빠진다 — 셀 것이 없다', 가른다([문('K2-01-E-0001', '   ')], {}).모르는코드.length === 0);
  잰다('창고에 본문 없는 문서가 있어도 선다',
    가른다([문('K2-01-E-0001', A)], { 'K2-01-E-0001': { code: 'K2-01-E-0001' } }).모르는코드.length === 1);
}

// ── 진짜 교재로 — «무엇이 문항인가»를 미주로 가르는 자리 ────────────────
// 🔴 위의 46가지는 «판정»만 잰다. 판정에 무엇이 들어가는지는 `교재읽기` 가 정하고,
//    거기서 틀리면 판정이 아무리 옳아도 답이 틀린다. 그래서 진짜 파일로 한 번 잰다.
// ⚠ 네트워크에 안 기댄다 — 창고 자리에 «손에 있는 본문»을 놓는다(`--local` 과 같은 길).
절('진짜 교재 다섯 파일 — 미주로 문항을 가른다');
{
  const fs = await import('fs');
  const path = await import('path');
  const { 교재읽기, 창고읽기_손에있는것, 교재폴더 } = await import('./store-diff.mjs');
  const 파일들 = fs.existsSync(교재폴더)
    ? fs.readdirSync(교재폴더).filter((x) => x.endsWith('.hwpx')).sort().map((x) => path.join(교재폴더, x))
    : [];
  if (!파일들.length) {
    console.log('  ⓘ 「교재 코드파일」 폴더가 없어 건너뜁니다 (다른 사람의 저장소에서는 정상입니다).');
  } else {
    const { 문항, 파일별 } = 교재읽기(파일들);
    const 앞장 = 파일별.reduce((a, x) => a + x.앞장, 0);
    잰다('문항 564제', 문항.length === 564);
    잰다('🔴 미주 없는 «앞장»(목차)을 뺐다 — 파일마다 하나씩 다섯', 앞장 === 5);
    잰다('🔴 그 다섯이 문항에 안 섞였다', !문항.some((m) => /평면좌표 \| 03/.test(m.content)));
    잰다('코드 없는 문항이 0 — 지금 교재는 다 심겨 있다', 문항.filter((m) => !m.code).length === 0);

    const { 창고 } = 창고읽기_손에있는것();
    잰다('손에 있는 본문 564제', Object.keys(창고).length === 564);
    const v = 가른다(문항, 창고);
    잰다('🔴 복사됨 0 — 지금 바닥이 깨끗하다', v.복사됨.length === 0);
    잰다('🔴 모르는 코드 0 — 파일의 코드가 전부 창고에 있다', v.모르는코드.length === 0);
    잰다('🔴 새 문항 0 · 코드잃음 0 — 다 이어진다', v.새문항.length === 0 && v.코드잃음.length === 0);
    잰다('⚠ 겹친 문항 1무리 (0311 = 0314)', v.겹침.length === 1);
    잰다('⑧ 빠진 것 0 — 다섯 단원이 다 왔다', v.빠졌다.length === 0);
    잰다('🔴 갈래 합이 564 — 하나도 안 새고 안 겹친다',
      v.그대로.length + v.고쳤다.length + v.모르는코드.length + v.코드잃음.length
      + v.새문항.length + v.복사됨.reduce((a, x) => a + x.무리.length, 0) === 564);
  }
}

console.log('\n  ' + (실패 ? '🔴' : '✅') + ' ' + 통과 + ' 통과 · ' + 실패 + ' 실패\n');
process.exit(실패 ? 1 : 0);
