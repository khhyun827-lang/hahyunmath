// 코드를 «개체 설명문»으로 숨겨도 그대로 읽히는가 (2026-09-10 · 사용자 요청)
//
//   node tools/code-hide-test.mjs
//
// 🔴 **붙드는 것은 «숨겨지나»가 아니라 «잃지 않나»다.** 코드를 옮기다 코드를 잃는 것이
//    이 일의 유일한 사고고, 그러면 창고와 교재를 잇는 끈이 끊긴다.
//
// 재는 것 셋:
//   ① 설명문에 숨긴 파일이 미주에 있던 것과 **똑같이** 읽히는가
//   ② 🔴 **미주가 설명문을 이기는가** — 사용자가 손으로 미주에 적으면 그것이 세야 한다
//      (「나는 매번 하나하나 개체설명문 열어서 코드를 쓸 수 없으니까」)
//   ③ 설명문 «글»이 본문에 새어 들지 않는가 — 새면 564제가 다 더러워진다
//
// ⚠ 네트워크에 안 기댄다. ⚠ 원본은 안 건드린다(임시 폴더로만 낸다).

import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { loadHwpxRules, problemsFromHwpx } from './hwpx-node.mjs';
import { 옮긴다, 훑는다, 교재폴더 } from './item-code-hide.mjs';
import { 푼다, 섹션들, 묶는다 } from './hwpx-zip.mjs';

let 통과 = 0, 실패 = 0;
const 잰다 = (이름, 참) => { 참 ? (통과++, console.log('  ✓ ' + 이름)) : (실패++, console.log('  ✗ ' + 이름)); };
const 절 = (s) => console.log('\n' + s);

const rules = loadHwpxRules();

// ── 규칙 하나만 따로 ──────────────────────────────────────────────────
절('HWP_SHAPE_CODE_RE — 설명문 «어디에서든» 코드를 찾는다');
{
  const R = rules.HWP_SHAPE_CODE_RE;
  잰다('안내문 뒤에 붙은 것을 문다', (('그림입니다. 원본 그림의 이름: 자산 12@4x.png [K2-01-E-0001]').match(R) || [])[1] === 'K2-01-E-0001');
  잰다('앞에 있어도 문다', (('[K2-01-E-0002] 그림입니다.').match(R) || [])[1] === 'K2-01-E-0002');
  잰다('②꼴(기출) 코드도 문다', (('그림입니다. [1230928OR]').match(R) || [])[1] === '1230928OR');
  잰다('변형 꼬리도 문다', (('[K2-01-E-0003-N01]').match(R) || [])[1] === 'K2-01-E-0003-N01');
  잰다('🔴 코드가 아니면 안 문다 — 「그림입니다.」', !R.test('그림입니다. 원본 그림의 이름: 자산 12@4x.png'));
  잰다('🔴 사람 이름도 안 문다', !R.test('장은영'));
  잰다('🔴 배점 대괄호를 헛짚지 않는다', !R.test('[3.5점]'));
  잰다('🔴 「[정답]」도 안 문다', !R.test('[정답] ②'));
}

if (!fs.existsSync(교재폴더)) {
  console.log('\n  ⓘ 교재 폴더가 없어 나머지는 건너뜁니다.');
  console.log('\n  ' + (실패 ? '🔴' : '✅') + ' ' + 통과 + ' 통과 · ' + 실패 + ' 실패\n');
  process.exit(실패 ? 1 : 0);
}
const 원본 = fs.readdirSync(교재폴더).filter((x) => /01\..*\.hwpx$/.test(x)).map((x) => path.join(교재폴더, x))[0];
if (!원본) { console.log('\n  ⓘ 01단원 교재가 없어 건너뜁니다.'); process.exit(0); }

const 뜰 = fs.mkdtempSync(path.join(os.tmpdir(), 'hide-test-'));
const 숨김 = path.join(뜰, '숨김.hwpx');
const 앞 = problemsFromHwpx(원본, rules).problems;
const 앞코드 = 앞.map((p) => p.itemCode || '');

// ── ① 숨겨도 똑같이 읽히는가 ─────────────────────────────────────────
절('① 미주 → 설명문으로 옮겨도 똑같이 읽힌다');
{
  const 전 = 훑는다(원본);
  잰다('원본은 미주 76 · 설명문 0', 전.미주 === 76 && 전.설명문 === 0);
  잰다('숨길 칸(문항 딱지)이 문항 수만큼 있다', 전.딱지 === 76);

  const r = 옮긴다(원본, 숨김);
  잰다('76개를 옮겼다', r.옮김 === 76);
  잰다('자리를 못 찾은 것이 없다', r.못찾음 === 0);

  const 후 = 훑는다(숨김);
  잰다('🔵 미주에서 사라지고 설명문으로 갔다', 후.미주 === 0 && 후.설명문 === 76);

  const 뒤 = problemsFromHwpx(숨김, rules).problems;
  잰다('🔴 **코드 76개가 한 글자도 안 달라졌다**', 뒤.map((p) => p.itemCode || '').join() === 앞코드.join());
  잰다('🔴 **본문도 한 글자도 안 달라졌다**', 뒤.every((p, i) => (p.content || '') === (앞[i].content || '')));
  잰다('정답(미주)도 그대로다 — 코드만 뺐지 정답은 안 건드렸다',
    뒤.every((p, i) => (p.answer || '') === (앞[i].answer || '')));
}

// ── ③ 설명문 글이 본문에 안 섞이는가 ─────────────────────────────────
절('③ 설명문 «글»이 본문에 안 새어 든다');
{
  const 뒤 = problemsFromHwpx(숨김, rules).problems;
  잰다('🔴 「그림입니다」가 본문에 없다', !뒤.some((p) => /그림입니다/.test(p.content || '')));
  잰다('🔴 「자산 12@4x」가 본문에 없다', !뒤.some((p) => /자산 12@4x/.test(p.content || '')));
  잰다('🔴 심어 둔 코드 글자가 본문에 없다', !뒤.some((p) => /K2-01-E-\d{4}/.test(p.content || '')));
}

// ── ② 미주가 설명문을 이기는가 ───────────────────────────────────────
절('② 🔴 손으로 미주에 적은 것이 «이긴다» (사용자가 정했다)');
{
  /* 숨긴 파일의 첫 미주에 «딴 코드»를 손으로 적어 넣고, 어느 쪽이 이기는지 본다. */
  const 손댄것 = path.join(뜰, '미주에도.hwpx');
  const { cdir, tmp } = 푼다(숨김);
  let 넣었나 = false;
  for (const s of 섹션들(cdir)) {
    if (넣었나) break;
    let xml = fs.readFileSync(s, 'utf8');
    const 새 = xml.replace(/(<hp:endNote\b[^>]*>[\s\S]*?<hp:t(?:\s[^>]*)?>)/, '$1[K2-01-E-9999]');
    if (새 !== xml) { fs.writeFileSync(s, 새); 넣었나 = true; }
  }
  묶는다(tmp, 손댄것);
  잰다('첫 미주에 손으로 딴 코드를 적었다', 넣었나);

  const 뒤 = problemsFromHwpx(손댄것, rules).problems;
  const 첫코드 = (뒤.find((p) => p.itemCode) || {}).itemCode;
  잰다('🔴 **미주에 적은 것이 이긴다** — 설명문의 코드를 누른다', 첫코드 === 'K2-01-E-9999');
  잰다('나머지는 설명문 그대로 읽힌다 (76개 다 있다)', 뒤.filter((p) => p.itemCode).length === 76);
}

// ── 되돌리기 ─────────────────────────────────────────────────────────
절('되돌릴 수 있다 — 도로 미주로');
{
  const 되돌린것 = path.join(뜰, '도로미주.hwpx');
  const r = 옮긴다(숨김, 되돌린것, { 되돌리기: true });
  잰다('76개를 도로 옮겼다', r.옮김 === 76);
  const 후 = 훑는다(되돌린것);
  잰다('🔵 설명문에서 사라지고 미주로 돌아왔다', 후.미주 === 76 && 후.설명문 === 0);
  const 뒤 = problemsFromHwpx(되돌린것, rules).problems;
  잰다('🔴 한 바퀴 돌아도 코드가 그대로다', 뒤.map((p) => p.itemCode || '').join() === 앞코드.join());
  잰다('🔴 본문도 그대로다', 뒤.every((p, i) => (p.content || '') === (앞[i].content || '')));
}

// ── 두 번 돌려도 안 겹치는가 ─────────────────────────────────────────
절('같은 일을 두 번 해도 두 번 안 박힌다');
{
  const 두번 = path.join(뜰, '두번.hwpx');
  const r = 옮긴다(숨김, 두번);
  잰다('이미 옮긴 파일은 더 옮길 것이 없다', r.옮김 === 0);
  const 후 = 훑는다(두번);
  잰다('설명문 코드가 76개 그대로 (두 벌이 안 됐다)', 후.설명문 === 76);
}

잰다('🔵 원본은 여전히 미주에 코드를 들고 있다 (한 글자도 안 고쳤다)', 훑는다(원본).미주 === 76);

fs.rmSync(뜰, { recursive: true, force: true });
console.log('\n  ' + (실패 ? '🔴' : '✅') + ' ' + 통과 + ' 통과 · ' + 실패 + ' 실패\n');
process.exit(실패 ? 1 : 0);
