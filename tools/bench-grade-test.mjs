// 검토 AI 채점기 검사 — 「같은 답을 다르게 적은 것」을 틀렸다고 세지 않는가
//
// 🔴 이 버그가 하루에 세 번 나왔다. 그래서 검사로 못 박는다.
//   ① 「2」와 「②」 — 번호를 동그라미 없이 적었다
//   ② 「-10」과 「①」 — 번호가 아니라 그 «값»을 적었다
//   ③ 「16/3」이 「16」으로 깎였다 — 분수의 앞자리만 집어냈다
//   셋 다 «맞은 답»인데 틀렸다고 셌다. 시험 점수만의 문제가 아니다 —
//   검토 기능에서 「두 AI가 답이 다릅니다」를 거짓으로 띄워 사람이 헛일을 하게 만든다.
//
// ⚠ 반대쪽도 지켜야 한다 — 숫자 2 를 언제나 ② 로 보면, 답이 2 인 «주관식»에서
//   아무 번호나 다 맞게 된다. 그래서 「창고 정답이 객관식일 때만」 옮긴다.
//
// ⚠ 시험 자료의 백슬래시는 문자코드로 넣는다 — 셸 헤어독을 지나면 깎여서
//   $" + "frac 이 폼피드가 되어 버린다(실제로 그랬다).

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const BS = String.fromCharCode(92);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(ROOT, 'tools', 'review-bench.mjs'), 'utf8');
const 조각 = src.slice(src.indexOf('const 동그라미'), src.indexOf('/* ⚠ 창고를 한 번만'));
const { 맞나, 값꼴, 보기들 } = new Function(조각 + '; return { 맞나, 값꼴, 보기들 };')();

const 보기5 = '$p q$의 값은? ① $- 10$ ② $-8$ ③ $- 6$ ④ $- 4$ ⑤ $- 2$';
const 분수보기 = '반지름의 곱은? ① $5$ ② $' + BS + 'frac{16}{3}$ ③ $' + BS + 'frac{17}{3}$ ④ $6$ ⑤ $' + BS + 'frac{19}{3}$';

const 것들 = [
  ['그대로 같으면 맞다',             ['②', '②', '객관식', 보기5], true],
  ['번호를 맨숫자로 적어도 맞다',    ['2', '②', '객관식', 보기5], true],
  ['번호가 다르면 틀리다',           ['3', '②', '객관식', 보기5], false],
  ['보기의 값으로 적어도 맞다',      ['-10', '①', '객관식', 보기5], true],
  ['다른 보기의 값이면 틀리다',      ['-8', '①', '객관식', 보기5], false],
  ['분수 값으로 적어도 맞다',        ['16/3', '②', '객관식', 분수보기], true],
  ['분수의 앞자리만은 틀리다',       ['16', '②', '객관식', 분수보기], false],
  ['주관식은 숫자를 그대로 견준다',  ['62', '62', '자연수', ''], true],
  ['주관식에서 2 는 ② 가 아니다',   ['2', '5', '자연수', ''], false],
  ['답이 없으면 맞을 수 없다',       ['', '②', '객관식', 보기5], false],
  ['보기가 없으면 값으로 못 맞춘다', ['9', '②', '객관식', '보기가 없는 글'], false],
];

let 흠 = 0;
for (const [이름, 인자, 바람] of 것들) {
  const 났다 = 맞나(...인자);
  if (났다 !== 바람) { 흠++; console.log('🔴 ' + 이름 + ' — 바란 것 ' + 바람 + ' · 나온 것 ' + 났다); }
}

const 값검사 = [
  [BS + 'frac{16}{3}', '16/3'],
  ['$- 10$', '-10'],
  ['$' + BS + 'left( 3 ' + BS + 'right)$', '3'],
  ['$9$', '9'],
];
for (const [넣은, 바람] of 값검사) {
  const 났다 = 값꼴(넣은);
  if (났다 !== 바람) { 흠++; console.log('🔴 값꼴 — ' + JSON.stringify(넣은) + ' → ' + JSON.stringify(났다) + ' (바란 것 ' + JSON.stringify(바람) + ')'); }
}

const 보 = 보기들(보기5);
if (!보 || 보[0] !== '-10' || 보[4] !== '-2') { 흠++; console.log('🔴 보기들 — ' + JSON.stringify(보)); }
if (보기들('동그라미가 없는 글') !== null) { 흠++; console.log('🔴 보기들 — 보기가 없는데 있다고 했다'); }

console.log(흠 ? '🔴 ' + 흠 + '개 어긋남' : '통과 ' + (것들.length + 값검사.length + 2) + '개');
process.exit(흠 ? 1 : 0);
