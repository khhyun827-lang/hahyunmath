// 주석만 걷어낸다 — «코드는 한 글자도 안 먹는» 방식으로 (2026-09-07)
//
// 🔴 **왜 따로 만들었나** — 검사 넷이 각자 이렇게 하고 있었다:
//     t.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '')
//   그런데 이건 **문자열 안의 `/*` 를 주석 시작으로 읽는다.** index.html 에는 그런 자리가
//   열한 곳 있고(스타일 글자 등), 하나가 가짜로 열리면 **다음 `*/` 까지 진짜 코드를 통째로 삼킨다.**
//   실측: 1,171,182자 → 836,789자. **29%가 사라졌다.**
//
//   🔴 그래서 「pw 를 쓰는 자리가 없다」 같은 검사가 **없어서가 아니라 먹혀서** 통과할 수 있었다.
//     검사가 조용히 눈이 머는 자리다 — 가장 나쁜 종류다.
//
// 🔵 **고친 방식** — 줄 단위로 본다. 이 프로젝트의 주석은 언제나 «줄 첫머리»에서 시작한다
//   (`/* …`, ` * …`, `// …`). 그래서 **줄이 그것으로 시작할 때만** 걷어낸다.
//   문자열 안의 `/*` 는 줄 첫머리에 오지 않으므로 건드리지 않는다.
//   ⚠ 대신 «코드 뒤에 붙은 꼬리 주석»은 안 걷힌다. 그건 괜찮다 —
//     검사가 찾는 것은 «코드가 있느냐»이고, 못 걷어낸 주석은 «있다»로 잘못 보게 할 뿐
//     (거짓 통과가 아니라 거짓 실패 쪽이다. 둘 중 안전한 쪽이다).

export function stripComments(src) {
  const 줄들 = String(src).replace(/\r\n/g, '\n').split('\n');
  const 나온것 = [];
  let 블록안 = false;
  for (const 줄 of 줄들) {
    const 앞 = 줄.trimStart();
    if (블록안) {
      나온것.push('');
      if (앞.includes('*/')) 블록안 = false;
      continue;
    }
    if (앞.startsWith('/*')) {
      나온것.push('');
      /* 한 줄짜리 블록 주석(/* … *​/)이면 거기서 닫힌다. */
      if (!앞.slice(2).includes('*/')) 블록안 = true;
      continue;
    }
    if (앞.startsWith('*') ||앞.startsWith('//')) { 나온것.push(''); continue; }
    나온것.push(줄);
  }
  return 나온것.join('\n');
}
