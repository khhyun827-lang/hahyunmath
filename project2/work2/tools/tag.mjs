// 문항마다 «수학적 표지»를 붙인다 — 4단원 «도형의 이동».
// 본문과 해설을 «둘 다» 본다: 해설에 풀이 전략이 드러나 있어 유형 판정에 제일 강한 근거다.

export const CONCEPTS = [
  // ── 이동의 종류 ─────────────────────────────────────────────
  ['TRANS', '평행이동', (t) => /평행이동|만큼 (평행)?이동|평행하게 이동/.test(t)],
  ['SYM', '대칭이동', (t) => /대칭이동|에 대하여 대칭|대칭인 점|대칭인 도형/.test(t)],
  ['BOTH_MOVE', '평행+대칭 결합', (t) => /평행이동/.test(t) && /대칭이동|대칭인/.test(t)],

  // ── 무엇을 옮기는가 ─────────────────────────────────────────
  ['LINE', '직선', (t) => /직선|일차함수|y *= *[a-z0-9-]+ *x/.test(t)],
  ['CIRCLE', '원', (t) => /원의 (방정식|중심)|반지름|\(x *[-+][^)]*\) *\^?\{?2\}? *\+ *\(y/.test(t)],
  ['PARABOLA', '포물선', (t) => /포물선|이차함수|꼭짓점|y *= *[^=]*x *\^ *\{?2/.test(t)],

  // ── 대칭의 축 ───────────────────────────────────────────────
  ['SYM_AXIS', 'x축·y축·원점 대칭', (t) => /[xy] *축에 대하여|원점에 대하여/.test(t)],
  ['SYM_YX', '직선 y=x·y=-x 대칭', (t) => /y *= *-? *x *에 대하여|기울기가.{0,8}[±+-] *1/.test(t)],
  ['SYM_POINT_AB', '점 (a,b)에 대한 대칭', (t) => /점 *\\? *left? *\(? *[a-z] *,~? *[a-z] *\)? *에 대하여|점.{0,12}에 대하여 대칭/.test(t)],
  // ⚠ 「직선 $y=x$ 에 대하여 대칭」은 «기본 연산»이지 일반 직선 대칭이 아니다.
  //    이것까지 T12 로 보내면 y=x 대칭 문항 수십 개가 통째로 상위 유형에 몰린다(실제로 그랬다).
  //    기울기·절편이 붙은 «진짜 일반 직선»일 때만 켠다.
  ['SYM_LINE_GEN', '일반 직선에 대한 대칭', (t) => {
    const ms = t.match(/직선[^.。]{0,40}?에 대하여 (?:대칭|서로 대칭)/g) || [];
    return ms.some((s) => !/y *= *-? *x(?![0-9a-z])/.test(s));
  }],

  // ── 특징적인 물음 ───────────────────────────────────────────
  ['FXY', '$f(x,y)=0$ 꼴', (t) => /f *\\? *left? *\(? *x *,~? *y *\)? *= *0|f\(x, *y\) *= *0/.test(t)],
  // ⚠ 「최솟값」만으로 잡으면 안 된다. 「…와 만나도록 하는 $k$ 의 최솟값」처럼
  //    거리와 무관한 최솟값 문항까지 최단거리 유형으로 끌려온다(실제로 그랬다).
  //    «거리·길이·선분»이 함께 나올 때만 켠다.
  ['MINDIST', '거리의 최솟값·최단 경로', (t) => /최단/.test(t)
    || (/최솟값|최소/.test(t) && /거리|길이|선분|\\bar|\\overline|둘레/.test(t))],
  ['LOCUS', '자취·조건을 만족시키는 점', (t) => /자취|나타내는 (방정식|도형)|조건을 만족시키는 점/.test(t)],
  ['AREA', '넓이', (t) => /넓이/.test(t)],
  ['INTERSECT', '교점·접함', (t) => /교점|접한다|접하도록|만나(지 않|는) *점/.test(t)],
  ['TANGENT', '접선·접점', (t) => /접선|접점/.test(t)],
  ['UNKNOWN', '미지수 역추적', (t) => /상수 *[a-z]|[a-z] *의 값(을|은|의)|모든 .{0,8}의 (합|곱)/.test(t)],
  ['GRAPH', '그래프 해석', (t) => /그래프|그림과 같이/.test(t)],
];

// 사고 단계를 재는 대리 지표 (난이도 판정의 재료)
export function features(p) {
  const t = p.body + '\n' + p.answer;
  const tags = CONCEPTS.filter(([, , f]) => f(t)).map(([k]) => k);
  const sol = p.answer;
  return {
    tags,
    n_tags: tags.length,
    sol_len: sol.length,
    cases: (sol.match(/\(ⅰ\)|\(ⅱ\)|\(i\)|\(ii\)|일 때/g) || []).length,
    boki: /<보기>|보기에서|ㄱ\.|ㄱ,/.test(p.body),
    unknown: /상수 *[a-z]|[a-z] *의 값/.test(t),
    maxmin: /최댓값|최솟값/.test(t),
    figure: p.has_figure,
    choice: p.is_choice,
    descriptive: /구하시오|나타내시오|쓰시오|보이시오/.test(p.body),
    body_len: p.body.length,
  };
}
