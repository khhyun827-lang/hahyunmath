// 내용으로 표준 유형을 정한다 (표가 굵거나 없는 문항용).
// ⚠ 순서가 곧 우선순위다. 위에 있을수록 «더 좁고 특징적인» 유형이다.
export function canonFromContent(f) {
  const has = (k) => f.tags.includes(k);
  if (has('MINDIST')) return 'T13';
  if (has('LOCUS')) return 'T14';
  if (has('SYM_POINT_AB')) return 'T11';
  if (has('SYM_LINE_GEN')) return 'T12';
  if (has('FXY')) return 'T10';
  // 평행+대칭이 «함께» 걸리면 결합 유형. y=x 대칭도 여기로 온다(기본 연산의 조합이므로)
  if (has('BOTH_MOVE')) return 'T09';
  if (has('SYM')) {
    if (has('PARABOLA')) return 'T08';
    if (has('CIRCLE')) return 'T07';
    if (has('LINE')) return 'T06';
    return 'T05';
  }
  if (has('TRANS')) {
    if (has('PARABOLA')) return 'T04';
    if (has('CIRCLE')) return 'T03';
    if (has('LINE')) return 'T02';
    return 'T01';
  }
  if (has('AREA') || has('INTERSECT')) return 'T15';
  return 'T01';
}
