// ① 체인 보수 — 「T○○ 가 담당한다」로만 적어 대표 ID 가 없던 것과, 대표가 지워진 것.
// ⚠ 셸(sed)로 고치면 백슬래시가 먹혀 LaTeX 가 깨진다. 반드시 이 파일로 돌린다.
import fs from 'fs';
const P = (f) => 'tools/' + f + '.mjs';

const FIX = [
  // [파일, 문항, 새 사유]  — 대표 ID 를 반드시 넣는다
  ['v2-t10', 'A-083',
    'C-064(T09) 와 같다 — 부분집합 «전체»에 걸쳐 원소의 합을 더하는 같은 틀이다'],
  ['v2-t22', 'A-048',
    'A-010(T08) 과 같다 — 원소의 미지수를 교집합 조건으로 확정한다'],
  ['v2-t22', 'B-094',
    'B-015(T07) 와 같다 — 원소가 구간에 들어갈 조건으로 미지수를 정한다'],
  ['v2-t22', 'D-051',
    'C-126(T19) 와 같다 — 범위 안 배수 집합의 개수를 포함배제로 센다'],
  ['v2-t15', 'D-016',
    'A-010(T08) 과 같다 — 원소에 든 미지수를 확정하는 것이 본체다'],
  ['v2-t12-t17', 'C-092',
    'A-022(T15) 와 같다 — 주어진 칸에서 집합을 복원한다'],
  ['v2-t12-t17', 'A-078',
    'C-072(T10) 와 같다 — 두 부분집합의 «순서쌍»을 조건에 맞춰 센다'],
  ['v2-t12-t17', 'B-056',
    'B-070(T19) 와 같다 — 배수 집합의 교집합을 최소공배수로 옮겨 센다'],
  ['v2-t11-basics', 'C-068',
    'C-052(T10) 와 같다 — 크기를 고정하고 조건에 맞춰 조합으로 센다'],
  ['v2-t11-basics', 'C-066',
    'B-076(T20) 과 같다 — 이차부등식 해집합의 겹침을 다룬다'],
];

let n = 0;
for (const [file, id, why] of FIX) {
  const path = P(file);
  const src = fs.readFileSync(path, 'utf8');
  // "'A-083': D(...)," 한 줄을 통째로 갈아 끼운다 (여러 줄에 걸친 것도 잡는다)
  const re = new RegExp("'" + id + "': D\\([\\s\\S]*?\\),\\n");
  if (!re.test(src)) { console.log('✗ 못 찾음 ' + file + ' / ' + id); continue; }
  fs.writeFileSync(path, src.replace(re, "'" + id + "': D('" + why + "'),\n"), 'utf8');
  n++;
}
console.log('고친 것 ' + n + ' / ' + FIX.length);
