// 내용으로 표준 유형을 정한다 (표를 못 믿는 문항용).
// ⚠ 순서가 곧 우선순위다. 위에 있을수록 «더 좁고 특징적인» 유형이다.
export function canonFromContent(f, t) {
  const has = (k) => f.tags.includes(k);
  if (has('COUNT_APPLY') && has('N_COUNT') && !f.maxmin) return 'T23';
  if (has('COUNT_MAXMIN')) return 'T22';
  if (has('NEW_OP')) return 'T18';
  if (has('SUBSET_SUM')) return 'T11';
  if (has('COUNT_FORMULA')) return 'T21';
  if (has('SUBSET_COUNT_C')) return 'T10';
  if (has('SUBSET_COUNT')) return 'T09';
  if (has('VENN')) return 'T15';
  if (has('DEMORGAN') || has('OP_LAWS') || has('OP_SIMPLIFY')) return 'T16';
  if (has('EQ_INEQ') && (has('UNION_INTER') || has('SUBSET_SYM'))) return 'T20';
  if (has('DIV_MUL') && (has('UNION_INTER') || has('N_COUNT'))) return 'T19';
  if (has('DISJOINT')) return 'T14';
  if (has('OP_SUBSET')) return 'T17';
  if (has('EQUAL_SET')) return 'T08';
  if (has('SUBSET_COND')) return 'T07';
  if (has('COMPL_DIFF')) return 'T13';
  if (has('N_COUNT') && !has('UNION_INTER')) return 'T03';
  if (has('UNION_INTER')) return 'T12';
  if (has('NEW_SET')) return 'T04';
  if (has('SUBSET_SYM') && has('ELEM_SYM')) return 'T05';
  if (has('SUBSET_SYM')) return 'T06';
  if (has('NOTATION')) return 'T02';
  if (has('SET_DEF') || has('ELEM_SYM')) return 'T01';
  if (has('FIN_INF')) return 'T03';
  return 'T01';
}
