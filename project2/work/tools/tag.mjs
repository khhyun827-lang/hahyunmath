// 사고 단계를 재는 대리 지표들 (난이도 판정의 재료)
export function features(p) {
  const t = p.body + '\n' + p.answer;
  const tags = CONCEPTS.filter(([, , f]) => f(t)).map(([k]) => k);
  const sol = p.answer;
  return {
    tags,
    n_tags: tags.length,
    // 해설이 길수록 풀이 단계가 많다
    sol_len: sol.length,
    // 경우를 나누는가 (ⅰ)(ⅱ) / i) / 일 때
    cases: (sol.match(/\(ⅰ\)|\(ⅱ\)|\(i\)|\(ii\)|일 때/g) || []).length,
    // 보기(ㄱㄴㄷ) 형태 = 여러 명제를 각각 판정해야 한다
    boki: /<보기>|보기에서|ㄱ\.|ㄱ,/.test(p.body),
    // 미지수가 있는가
    unknown: /(미지수|실수 [a-z] *의 값|정수 [a-z]|모든 .{0,8}의 (합|곱))/.test(t),
    maxmin: /최댓값|최솟값/.test(t),
    figure: p.has_figure,
    choice: p.is_choice,
    // 서술형(구하시오) 인가
    descriptive: /구하시오|나타내시오|쓰시오|보이시오/.test(p.body),
    body_len: p.body.length,
  };
}
